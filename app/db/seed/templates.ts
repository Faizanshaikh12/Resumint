const escapeSql = (str: string) => str.replace(/'/g, "''");

export function generateTemplateSeedStatements(): string[] {
  const now = Date.now();
  return TEMPLATE_SEED_DATA.map((t) => {
    const designJson = escapeSql(JSON.stringify(t.design));
    const layoutJson = escapeSql(JSON.stringify(t.layout));
    const sampleJson = t.sampleContent ? `'${escapeSql(JSON.stringify(t.sampleContent))}'` : "NULL";
    const name = escapeSql(t.name);
    const description = escapeSql(t.description);

    return `INSERT INTO "template_master" ("id", "key", "name", "description", "tier", "design", "layout", "sample_content", "sort_order", "is_active", "version", "created_at", "updated_at") VALUES ('${t.id}', '${t.key}', '${name}', '${description}', '${t.tier}', '${designJson}', '${layoutJson}', ${sampleJson}, ${t.sortOrder}, ${t.isActive ? 1 : 0}, ${t.version}, ${now}, ${now}) ON CONFLICT ("key") DO UPDATE SET "name" = excluded."name", "description" = excluded."description", "tier" = excluded."tier", "design" = excluded."design", "layout" = excluded."layout", "sample_content" = excluded."sample_content", "sort_order" = excluded."sort_order", "is_active" = excluded."is_active", "version" = excluded."version", "updated_at" = excluded."updated_at";`;
  });
}

export function generateTemplateSeedSql(): string {
  return generateTemplateSeedStatements().join("\n");
}

